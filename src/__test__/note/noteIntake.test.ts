import { describe, expect, it } from "vitest";

import { createObjectId } from "@/utils/clientHelpers";
import { removeDoneProjectNotes, upsertNote } from "@/utils/note/noteIntake";
import { attachOrUpdateShare } from "@/utils/share/shareIntake";

import { rawData } from "../db/rawData";
import { seedNote as seedAnyNote, seedProject, seedUser, sortById, testId } from "../db/seed";
import { BACKENDS, useTestStore } from "../db/testStores";

const noteInput = (projectId: string, overrides: Record<string, unknown> = {}) => ({
  _id: testId(),
  content: "Trim the intro",
  time: 12,
  done: false,
  project: projectId,
  ...overrides,
});

const guest = () => null;
const visitor = (ids: { visitorId: string }) => ids.visitorId;

describe.each(BACKENDS)("Note intake: %s", (backend) => {
  const store = useTestStore(backend);

  const seed = async (share?: { canEdit: boolean }) => {
    const owner = await seedUser(store(), "owner@example.com", { username: "owner" });
    const visitor = await seedUser(store(), "visitor@example.com", { username: "visitor" });
    const project = await seedProject(store(), owner._id, { title: "Rough cut" });
    if (share) await attachOrUpdateShare(project, { url: "rough-cut", ...share });
    return { ownerId: owner._id, visitorId: visitor._id, projectId: project._id };
  };

  const seedNote = (
    projectId: string,
    fields: { time?: number; done?: boolean; authorId?: string } = {},
  ) => seedAnyNote(store(), projectId, { content: "Original", ...fields });

  const noteIds = async (projectId: string) =>
    (await store().listNotes(projectId)).map((note) => note._id);

  describe("upsertNote on create", () => {
    it("lets the owner create a Note, linking it to the Project with its author", async () => {
      const { ownerId, projectId } = await seed();
      const input = noteInput(projectId);

      const result = await upsertNote(input, ownerId);

      if (result.kind !== "ok") throw new Error(`expected ok, got ${result.kind}`);
      expect(result.note).toMatchObject({
        content: "Trim the intro",
        user: { _id: ownerId, username: "owner", role: "owner" },
      });
      expect(JSON.stringify(result.note)).not.toContain("owner@example.com");
      expect((await store().loadProject(projectId))!.notes.map((note) => note._id)).toEqual([
        input._id,
      ]);
    });

    it("accepts a Note id generated by the client", async () => {
      const { ownerId, projectId } = await seed();
      const input = noteInput(projectId, { _id: createObjectId() });

      const result = await upsertNote(input, ownerId);

      expect(result.kind).toBe("ok");
      expect((await store().getNote(input._id))?.content).toBe("Trim the intro");
    });

    it.each([
      ["a guest", guest],
      ["another user", visitor],
    ])("forbids %s without a Share", async (_label, caller) => {
      const ids = await seed();

      const input = noteInput(ids.projectId);
      expect(await upsertNote(input, caller(ids))).toEqual({ kind: "forbidden" });
      expect(await store().getNote(input._id)).toBeNull();
      expect((await store().loadProject(ids.projectId))!.notes).toHaveLength(0);
    });

    it.each([
      ["a guest", guest],
      ["another user", visitor],
    ])("forbids %s when the Share has canEdit false", async (_label, caller) => {
      const ids = await seed({ canEdit: false });

      const input = noteInput(ids.projectId);
      expect(await upsertNote(input, caller(ids))).toEqual({ kind: "forbidden" });
      expect(await store().getNote(input._id)).toBeNull();
      expect(await noteIds(ids.projectId)).toEqual([]);
    });

    it("lets a guest create through an editable Share, without an author", async () => {
      const { ownerId, projectId } = await seed({ canEdit: true });

      const input = noteInput(projectId, { user: ownerId });
      const result = await upsertNote(input, null);

      expect(result.kind).toBe("ok");
      const stored = await store().getNote(input._id);
      expect(stored).not.toHaveProperty("authorId");
      expect((await store().loadProject(projectId))!.notes).toHaveLength(1);
    });

    it("lets another user create through an editable Share as themselves", async () => {
      const { ownerId, visitorId, projectId } = await seed({ canEdit: true });

      const input = noteInput(projectId, { user: ownerId });
      const result = await upsertNote(input, visitorId);

      expect((await store().getNote(input._id))!.authorId).toBe(visitorId);
      if (result.kind !== "ok") throw new Error(`expected ok, got ${result.kind}`);
      expect(result.note.user).toEqual({ _id: visitorId, username: "visitor", role: "member" });
    });

    it("returns notFound for a missing Project and saves nothing", async () => {
      const { ownerId } = await seed();

      const input = noteInput(testId());
      expect(await upsertNote(input, ownerId)).toEqual({ kind: "notFound" });
      expect(await store().getNote(input._id)).toBeNull();
    });

    it.each([["not-an-id"], [{ $ne: null }], [{ _bsontype: "ObjectId", $ne: null }], [undefined]])(
      "returns invalid for the malformed Project id %j and saves nothing",
      async (project) => {
        const { ownerId, projectId } = await seed();

        const input = noteInput(projectId, { project });
        expect(await upsertNote(input, ownerId)).toEqual({ kind: "invalid" });
        expect(await store().getNote(input._id)).toBeNull();
        expect(await noteIds(projectId)).toEqual([]);
      },
    );

    it.each([["not-an-id"], [{ $ne: null }], [{ _bsontype: "ObjectId", $ne: null }], [42], [null]])(
      "returns invalid for the malformed Note id %j and saves nothing",
      async (_id) => {
        const { ownerId, projectId } = await seed();
        await seedNote(projectId, { authorId: ownerId });

        expect(await upsertNote(noteInput(projectId, { _id }), ownerId)).toEqual({
          kind: "invalid",
        });
        expect((await store().listNotes(projectId)).map((note) => note.content)).toEqual([
          "Original",
        ]);
      },
    );
  });

  describe("upsertNote field validation", () => {
    it.each([
      ["no content", { content: undefined }],
      ["empty content", { content: "" }],
      ["non-string content", { content: { $gt: "" } }],
      ["a non-number time", { time: "soon" }],
      ["a non-finite time", { time: Number.NaN }],
      ["a non-boolean done", { done: "yes" }],
    ])("returns invalid on create with %s and saves nothing", async (_label, overrides) => {
      const { ownerId, projectId } = await seed();

      const input = noteInput(projectId, overrides);
      expect(await upsertNote(input, ownerId)).toEqual({ kind: "invalid" });
      expect(await store().getNote(input._id)).toBeNull();
      expect(await noteIds(projectId)).toEqual([]);
    });

    it.each([
      ["empty content", { content: "" }],
      ["a non-number time", { time: "soon" }],
      ["a non-boolean done", { done: 0 }],
    ])(
      "returns invalid on update with %s and leaves the Note unchanged",
      async (_label, fields) => {
        const { ownerId, projectId } = await seed();
        const note = await seedNote(projectId, { authorId: ownerId, time: 3 });

        const result = await upsertNote(
          { _id: note._id, project: projectId, ...fields } as never,
          ownerId,
        );

        expect(result).toEqual({ kind: "invalid" });
        expect(await store().getNote(note._id)).toMatchObject({ content: "Original", time: 3 });
      },
    );

    it.each([
      ["no time", { time: undefined }],
      ["a null time", { time: null }],
    ])("creates with time 0 given %s", async (_label, overrides) => {
      const { ownerId, projectId } = await seed();
      const input = noteInput(projectId, overrides);

      const result = await upsertNote(input as never, ownerId);

      expect(result.kind).toBe("ok");
      expect(await store().getNote(input._id)).toMatchObject({
        content: "Trim the intro",
        time: 0,
      });
    });

    it("leaves the time unchanged on an update with a null time", async () => {
      const { ownerId, projectId } = await seed();
      const note = await seedNote(projectId, { authorId: ownerId, time: 3 });

      const result = await upsertNote(
        { _id: note._id, project: projectId, content: "Edited", time: null } as never,
        ownerId,
      );

      expect(result.kind).toBe("ok");
      expect(await store().getNote(note._id)).toMatchObject({ content: "Edited", time: 3 });
    });

    it("leaves done unchanged on an update with a null done", async () => {
      const { ownerId, projectId } = await seed();
      const note = await seedNote(projectId, { authorId: ownerId, done: true });

      const result = await upsertNote(
        { _id: note._id, project: projectId, content: "Edited", done: null } as never,
        ownerId,
      );

      expect(result.kind).toBe("ok");
      expect(await store().getNote(note._id)).toMatchObject({ content: "Edited", done: true });
    });

    it("creates with done false given a null done", async () => {
      const { ownerId, projectId } = await seed();
      const input = noteInput(projectId, { done: null });

      const result = await upsertNote(input as never, ownerId);

      expect(result.kind).toBe("ok");
      expect(await store().getNote(input._id)).toMatchObject({ done: false });
    });

    it("lets an update omit content", async () => {
      const { ownerId, projectId } = await seed();
      const note = await seedNote(projectId, { authorId: ownerId });

      const result = await upsertNote(
        { _id: note._id, project: projectId, done: true } as never,
        ownerId,
      );

      expect(result.kind).toBe("ok");
      expect(await store().getNote(note._id)).toMatchObject({ content: "Original", done: true });
    });
  });

  describe("upsertNote on update", () => {
    it("lets the owner update content, time and done", async () => {
      const { ownerId, projectId } = await seed();
      const note = await seedNote(projectId, { authorId: ownerId });

      const result = await upsertNote(
        noteInput(projectId, { _id: note._id, content: "Edited", time: 40, done: true }),
        ownerId,
      );

      expect(result.kind).toBe("ok");
      expect(await store().getNote(note._id)).toMatchObject({
        content: "Edited",
        time: 40,
        done: true,
      });
    });

    it("leaves fields the payload omits untouched", async () => {
      const { ownerId, projectId } = await seed();
      const note = await seedNote(projectId, { time: 40, done: true });

      await upsertNote({ _id: note._id, content: "Edited", project: projectId }, ownerId);

      expect(await store().getNote(note._id)).toMatchObject({
        content: "Edited",
        time: 40,
        done: true,
      });
    });

    it("decides permission from the stored Note's Project, not the payload", async () => {
      const { ownerId, projectId: privateProjectId } = await seed();
      const editable = await seedProject(store(), ownerId, { title: "Open" });
      await attachOrUpdateShare(editable, { url: "open", canEdit: true });
      const note = await seedNote(privateProjectId);

      const result = await upsertNote(
        noteInput(editable._id, { _id: note._id, content: "Changed" }),
        null,
      );

      expect(result).toEqual({ kind: "forbidden" });
      expect((await store().getNote(note._id))!.content).toBe("Original");
    });

    it("keeps project and user when the payload tries to change them", async () => {
      const { ownerId, visitorId, projectId } = await seed({ canEdit: true });
      const other = await seedProject(store(), visitorId, { title: "Other" });
      const note = await seedNote(projectId, { authorId: ownerId });

      const result = await upsertNote(
        noteInput(other._id, { _id: note._id, content: "Edited", user: visitorId }),
        visitorId,
      );

      expect(result.kind).toBe("ok");
      const stored = (await store().getNote(note._id))!;
      expect(stored.content).toBe("Edited");
      expect(stored.projectId).toBe(projectId);
      expect(stored.authorId).toBe(ownerId);
      expect(await noteIds(projectId)).toEqual([note._id]);
      expect((await store().loadProject(other._id))!.notes).toHaveLength(0);
    });

    it("returns notFound when the stored Note's Project is gone", async () => {
      const { ownerId, projectId } = await seed();
      const note = await seedNote(projectId);
      await rawData().removeProjectOnly(projectId);

      const result = await upsertNote(noteInput(projectId, { _id: note._id }), ownerId);

      expect(result).toEqual({ kind: "notFound" });
    });
  });

  describe("removeDoneProjectNotes", () => {
    it("lets the owner remove done Notes, pulling them from the Project", async () => {
      const { ownerId, projectId } = await seed();
      const done = await seedNote(projectId, { done: true });
      const open = await seedNote(projectId);

      const result = await removeDoneProjectNotes(projectId, ownerId);

      if (result.kind !== "ok") throw new Error(`expected ok, got ${result.kind}`);
      expect(result.notes.map((note) => note._id)).toEqual([open._id]);
      expect(await store().getNote(done._id)).toBeNull();
      expect((await store().loadProject(projectId))!.notes.map((note) => note._id)).toEqual([
        open._id,
      ]);
    });

    it("returns the survivors with their authors as the public view", async () => {
      const { ownerId, visitorId, projectId } = await seed();
      await store().updateProfile(visitorId, { username: "visitor@example.com" });
      await seedNote(projectId, { authorId: ownerId });
      await seedNote(projectId, { authorId: visitorId });
      await seedNote(projectId);

      const result = await removeDoneProjectNotes(projectId, ownerId);

      if (result.kind !== "ok") throw new Error(`expected ok, got ${result.kind}`);
      expect(sortById(result.notes).map((note) => note.user)).toEqual([
        { _id: ownerId, username: "owner", role: "owner" },
        { _id: visitorId, role: "member" },
        undefined,
      ]);
      expect(JSON.stringify(result.notes)).not.toMatch(/@example\.com/);
    });

    it("lets a guest remove done Notes through an editable Share", async () => {
      const { projectId } = await seed({ canEdit: true });
      await seedNote(projectId, { done: true });
      const open = await seedNote(projectId);

      const result = await removeDoneProjectNotes(projectId, null);

      if (result.kind !== "ok") throw new Error(`expected ok, got ${result.kind}`);
      expect(result.notes.map((note) => note._id)).toEqual([open._id]);
      expect(await noteIds(projectId)).toEqual([open._id]);
    });

    it.each([
      ["a guest", guest],
      ["another user", visitor],
    ])("forbids %s when the Share has canEdit false", async (_label, caller) => {
      const ids = await seed({ canEdit: false });
      const done = await seedNote(ids.projectId, { done: true });

      expect(await removeDoneProjectNotes(ids.projectId, caller(ids))).toEqual({
        kind: "forbidden",
      });
      expect(await noteIds(ids.projectId)).toEqual([done._id]);
    });

    it("returns notFound for a missing Project", async () => {
      const { ownerId } = await seed();

      expect(await removeDoneProjectNotes(testId(), ownerId)).toEqual({
        kind: "notFound",
      });
    });

    it.each([["not-an-id"], [{ $ne: null }], [{ _bsontype: "ObjectId", $ne: null }], [undefined]])(
      "returns invalid for the malformed project id %j",
      async (projectId) => {
        const { ownerId } = await seed();

        expect(await removeDoneProjectNotes(projectId, ownerId)).toEqual({ kind: "invalid" });
      },
    );
  });
});
